-- ============================================================
-- Предпочтения / ограничения гостя (свободный текст на место за столом).
--
-- Официант фиксирует пожелания гостя при описании («без чеснока», «не любит
-- острое», «аллергия на орехи», «без лука»). Текст уходит в ИИ-помощника меню
-- (api/_lib/suggestCore.js → buildMessages): такие блюда НЕ предлагаются. Одно
-- поле на место (seat_number), как и остальные атрибуты гостя.
--
-- Полностью идемпотентно и обратносовместимо: это просто новая NULL-колонка,
-- существующие политики RLS на order_guests её покрывают (пишет то же
-- устройство/официант, что и остальные атрибуты). Код (loadGuestAttributes /
-- saveGuestAttributes) написан защитно и работает и ДО применения миграции —
-- просто без сохранения предпочтений, пока колонки нет.
--
-- Запускать из-под supabase_admin:
--   sudo docker exec -i supabase-db psql -U supabase_admin -d postgres \
--     -v ON_ERROR_STOP=1 < supabase/migrations/20260831010000_guest_preferences.sql
-- ============================================================

BEGIN;

ALTER TABLE public.order_guests
  ADD COLUMN IF NOT EXISTS preferences text;

COMMENT ON COLUMN public.order_guests.preferences IS
  'Свободный текст: пожелания/ограничения гостя (без чеснока, аллергии и т.п.). Уходит в ИИ-помощника меню как исключающее условие.';

COMMIT;
