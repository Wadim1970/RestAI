-- ============================================================
-- «Скрыто от гостя» для блюд: раздел или блюдо есть в меню ресторана (его
-- видит и продаёт официант), но в гостевом приложении, у голосового
-- помощника и в парах блюд его нет. Например «Лавка» (продукты навынос),
-- комбо-наборы.
--
-- Гостевое /api/menu отдаёт только is_hidden = false; пары блюд (Waiter-app,
-- api/pairings) считают скрытые блюда недоступными.
--
-- Идемпотентно. Запускать из-под supabase_admin (или в Studio → SQL Editor).
-- ============================================================

BEGIN;

ALTER TABLE public.menu_items
  ADD COLUMN IF NOT EXISTS is_hidden boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.menu_items.is_hidden IS
  'Скрыто от гостя: нет в гостевом меню, у голосового помощника и в парах блюд. Официант видит.';

COMMIT;
